import React, { useMemo } from 'react';
import { useApp } from '../../context/AppContext';
import {
  calculateCustomerPerformance,
  calculateTotalNetRevenue,
  formatCurrency,
} from '../../engine/calculations';
import {
  Users,
  UserCheck,
  AlertTriangle,
  Calendar,
  Building,
  ShieldAlert,
} from 'lucide-react';

export const CustomersView: React.FC = () => {
  const { filteredTransactions, currency, language } = useApp();

  const customers = useMemo(() => {
    return calculateCustomerPerformance(filteredTransactions);
  }, [filteredTransactions]);

  const totalRevenue = useMemo(() => {
    return calculateTotalNetRevenue(filteredTransactions);
  }, [filteredTransactions]);

  // Pareto Analysis: what % of revenue is generated by top 20% of customers?
  const paretoSummary = useMemo(() => {
    if (customers.length === 0) return { top20Count: 0, top20RevenueShare: 0, isHighConcentration: false };

    const top20Count = Math.max(1, Math.round(customers.length * 0.2));
    const top20Rev = customers.slice(0, top20Count).reduce((acc, c) => acc + c.totalRevenue, 0);
    const top20RevenueShare = totalRevenue > 0 ? Math.round((top20Rev / totalRevenue) * 1000) / 10 : 0;

    return {
      top20Count,
      top20RevenueShare,
      isHighConcentration: top20RevenueShare > 70,
    };
  }, [customers, totalRevenue]);

  const repeatCustomersCount = useMemo(() => {
    return customers.filter((c) => c.isRepeat).length;
  }, [customers]);

  const decliningCustomers = useMemo(() => {
    return customers.filter((c) => c.isDeclining);
  }, [customers]);

  return (
    <div className="space-y-6">
      {/* Customer Insights Banner */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        {/* Total Customers */}
        <div className="bg-white border border-slate-200 rounded-xl p-4 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-xs font-bold text-slate-500">
              {language === 'ar' ? 'إجمالي العملاء النشطين' : 'Active Client Accounts'}
            </span>
            <div className="text-2xl font-extrabold text-slate-900 mt-1">
              {customers.length}
            </div>
            <span className="text-[11px] text-slate-400">
              {language === 'ar' ? 'في الفترة الزمنية المحددة' : 'In selected window'}
            </span>
          </div>
          <div className="w-10 h-10 rounded-lg bg-teal-50 text-teal-700 flex items-center justify-center">
            <Users size={20} />
          </div>
        </div>

        {/* Repeat vs New */}
        <div className="bg-white border border-slate-200 rounded-xl p-4 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-xs font-bold text-slate-500">
              {language === 'ar' ? 'العملاء المتكررون (Repeat)' : 'Repeat Customers'}
            </span>
            <div className="text-2xl font-extrabold text-emerald-700 mt-1">
              {repeatCustomersCount}
            </div>
            <span className="text-[11px] text-slate-400">
              {customers.length > 0
                ? `${Math.round((repeatCustomersCount / customers.length) * 100)}% ${
                    language === 'ar' ? 'من إجمالي المتعاملين' : 'of active accounts'
                  }`
                : '—'}
            </span>
          </div>
          <div className="w-10 h-10 rounded-lg bg-emerald-50 text-emerald-700 flex items-center justify-center">
            <UserCheck size={20} />
          </div>
        </div>

        {/* Pareto Concentration */}
        <div className="bg-white border border-slate-200 rounded-xl p-4 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-xs font-bold text-slate-500">
              {language === 'ar' ? 'تركيز المبيعات (قاعدة 80/20)' : 'Pareto Concentration'}
            </span>
            <div className="text-2xl font-extrabold text-slate-900 mt-1">
              {paretoSummary.top20RevenueShare}%
            </div>
            <span className="text-[11px] text-slate-400">
              {language === 'ar'
                ? `تحققها أعلى ${paretoSummary.top20Count} عملاء فقط`
                : `Generated by top ${paretoSummary.top20Count} clients`}
            </span>
          </div>
          <div className="w-10 h-10 rounded-lg bg-amber-50 text-amber-700 flex items-center justify-center">
            <AlertTriangle size={20} />
          </div>
        </div>
      </div>

      {/* Churn Warning if declining customers found */}
      {decliningCustomers.length > 0 && (
        <div className="alert-box warning">
          <ShieldAlert size={20} className="text-amber-700 flex-shrink-0" />
          <div className="text-xs">
            <span className="font-bold block text-sm mb-0.5">
              {language === 'ar'
                ? `تنبيه ركود النشاط لـ (${decliningCustomers.length}) عملاء`
                : `Dormancy warning for (${decliningCustomers.length}) client accounts`}
            </span>
            <p>
              {language === 'ar'
                ? 'متاجر وعملاء اعتياديون لم يقوموا بأي طلبية جديدة منذ أكثر من 45 يوماً. نوصي بتواصل مندوب المبيعات معهم لمعرفة الأسباب.'
                : 'Regular buyers who have not placed a reorder in over 45 days. Account manager follow-up is recommended.'}
            </p>
          </div>
        </div>
      )}

      {/* Customer Analytics Table */}
      <div className="table-container shadow-xs">
        <table className="data-table">
          <thead>
            <tr>
              <th>{language === 'ar' ? 'كود العميل' : 'Client ID'}</th>
              <th>{language === 'ar' ? 'اسم العميل / المتجر' : 'Client / Store Name'}</th>
              <th>{language === 'ar' ? 'المحافظة' : 'Region'}</th>
              <th>{language === 'ar' ? 'عدد الطلبات' : 'Orders'}</th>
              <th>{language === 'ar' ? 'إجمالي المشتريات' : 'Total Revenue'}</th>
              <th>{language === 'ar' ? 'نسبة التركيز %' : 'Share %'}</th>
              <th>{language === 'ar' ? 'متوسط قيمة الطلب' : 'AOV'}</th>
              <th>{language === 'ar' ? 'تاريخ آخر طلب' : 'Last Order Date'}</th>
              <th>{language === 'ar' ? 'حالة النشاط' : 'Activity Status'}</th>
            </tr>
          </thead>
          <tbody>
            {customers.map((c) => (
              <tr key={c.customerId}>
                <td className="font-mono text-xs font-bold text-slate-500">
                  {c.customerId}
                </td>
                <td>
                  <div className="font-bold text-slate-900">{c.customerName}</div>
                </td>
                <td>
                  <span className="badge badge-neutral">{c.region}</span>
                </td>
                <td className="font-bold text-slate-800">{c.orderCount}</td>
                <td className="font-extrabold text-teal-800">
                  {formatCurrency(c.totalRevenue, currency, language)}
                </td>
                <td>
                  <span
                    className={`font-bold text-xs ${
                      c.revenueSharePercent >= 20 ? 'text-amber-600 font-extrabold' : 'text-slate-700'
                    }`}
                  >
                    {c.revenueSharePercent}%
                  </span>
                </td>
                <td className="text-slate-700 font-medium">
                  {formatCurrency(c.avgOrderValue, currency, language)}
                </td>
                <td className="text-slate-500 text-xs">{c.lastOrderDate || '—'}</td>
                <td>
                  {c.isDeclining ? (
                    <span className="badge badge-warning">
                      {language === 'ar' ? 'متأخر في الطلب (>45 يوم)' : 'Dormant (>45d)'}
                    </span>
                  ) : c.isRepeat ? (
                    <span className="badge badge-success">
                      {language === 'ar' ? 'عميل منتظم' : 'Regular Buyer'}
                    </span>
                  ) : (
                    <span className="badge badge-neutral">
                      {language === 'ar' ? 'عميل جديد' : 'New Account'}
                    </span>
                  )}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
};
